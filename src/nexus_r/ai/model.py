"""Hypothesis model.

A Hypothesis is an AI-generated (or template-generated) commentary on
an existing finding or attack path. It is NOT a finding:

- It never introduces new evidence.
- It always references at least one existing finding or attack path.
- It always has validation_steps and a status of `needs_review`.
- It is never trusted without human validation (ADR-001 §3.7).
"""

from __future__ import annotations

from datetime import datetime, timezone
from enum import Enum
from typing import Any

from pydantic import BaseModel, ConfigDict, Field

from nexus_r.analysis.finding import Confidence, Severity


class HypothesisMode(str, Enum):
    TEMPLATE = "template"   # generated without AI (offline fallback)
    OLLAMA = "ollama"       # generated by an Ollama local model
    OPENAI = "openai"       # generated by an OpenAI-compatible API


class HypothesisStatus(str, Enum):
    NEEDS_REVIEW = "needs_review"
    ACCEPTED = "accepted"
    REJECTED = "rejected"


def _utc_now() -> datetime:
    return datetime.now(timezone.utc)


class Hypothesis(BaseModel):
    """An AI/template commentary on a finding or attack path."""

    model_config = ConfigDict(extra="forbid", frozen=True)

    id: str = Field(..., min_length=1)
    finding_ids: tuple[str, ...] = ()
    attack_path_ids: tuple[str, ...] = ()
    mode: HypothesisMode = HypothesisMode.TEMPLATE
    model: str = "template"
    title: str = Field(..., min_length=1)
    narrative: str = ""
    severity: Severity = Severity.INFO
    confidence: Confidence = Confidence.LOW
    status: HypothesisStatus = HypothesisStatus.NEEDS_REVIEW
    validation_steps: tuple[str, ...] = ()
    references: tuple[str, ...] = ()
    tags: tuple[str, ...] = ()
    created_at: datetime = Field(default_factory=_utc_now)

    def to_json_dict(self) -> dict[str, Any]:
        return self.model_dump(mode="json")
